export function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>'"]/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", "'": "&#39;", '"': "&quot;",
  }[character]));
}

function currency(value, code, locale) {
  return new Intl.NumberFormat(locale, { style: "currency", currency: code, minimumFractionDigits: 2 }).format(Number(value || 0));
}

function compactCurrency(value, code, locale) {
  return new Intl.NumberFormat(locale, { style: "currency", currency: code, notation: "compact", maximumFractionDigits: 1 }).format(Number(value || 0));
}

function duration(seconds) {
  const totalMinutes = Math.round(Number(seconds || 0) / 60);
  return `${Math.floor(totalMinutes / 60)}h ${String(totalMinutes % 60).padStart(2, "0")}m`;
}

function periodLabel(report, copy, locale = "en-US") {
  if (report.reportType === "daily") return dateKey(report.summary.period.date, locale);
  if (report.reportType === "monthly") return new Intl.DateTimeFormat(locale, { timeZone: "UTC", month: "long", year: "numeric" }).format(new Date(Date.UTC(report.summary.period.year, report.summary.period.month - 1, 1)));
  return String(report.summary.period.year);
}

function activityMetric(bucket, type, field) {
  return Number(bucket?.activities?.find((activity) => activity.type === type)?.[field] || 0);
}

function monthName(year, month, locale) {
  return new Intl.DateTimeFormat(locale, { timeZone: "UTC", month: "short" }).format(new Date(Date.UTC(year, month - 1, 1)));
}

function monthlyRows(report, locale) {
  const businessDate = report.summary.period.businessDate || "9999-12-31";
  return report.summary.days.map((bucket) => {
    const future = bucket.key > businessDate;
    const values = Object.fromEntries(series.map(({ key }) => [key, future ? null : activityMetric(bucket, key, "revenue")]));
    const sessions = Object.fromEntries(series.map(({ key }) => [key, future ? null : activityMetric(bucket, key, "sessions")]));
    return {
      key: bucket.key,
      label: String(Number(bucket.key.slice(-2))),
      future,
      values,
      sessions,
      total: future ? null : series.reduce((sum, item) => sum + values[item.key], 0),
      sessionTotal: future ? null : series.reduce((sum, item) => sum + sessions[item.key], 0),
      tooltip: new Intl.DateTimeFormat(locale, { timeZone: "UTC", month: "short", day: "numeric" }).format(new Date(`${bucket.key}T12:00:00Z`)),
    };
  });
}

function yearlyRows(report, locale) {
  const currentMonth = (report.summary.period.businessDate || "9999-12").slice(0, 7);
  return report.summary.months.map((bucket, index) => {
    const future = bucket.key > currentMonth;
    const values = Object.fromEntries(series.map(({ key }) => [key, future ? 0 : activityMetric(bucket, key, "revenue")]));
    return {
      key: bucket.key,
      label: monthName(report.summary.period.year, index + 1, locale),
      future,
      values,
      total: future ? 0 : series.reduce((sum, item) => sum + values[item.key], 0),
    };
  });
}

function sessionInterval(session, periodStart, periodEnd) {
  const rawStart = new Date(session.startedAt).getTime();
  if (!Number.isFinite(rawStart)) return null;
  let rawEnd = session.endedAt ? new Date(session.endedAt).getTime() : periodEnd;
  if (session.status === "paused" && session.pausedAt) rawEnd = Math.min(rawEnd, new Date(session.pausedAt).getTime());
  const start = Math.max(rawStart, periodStart);
  const end = Math.min(Number.isFinite(rawEnd) ? rawEnd : periodEnd, periodEnd);
  return end > start && series.some((item) => item.key === session.activity) ? { start, end, type: session.activity } : null;
}

function maximumConcurrency(intervals, bucketStart, bucketEnd, type) {
  const changes = new Map();
  for (const interval of intervals) {
    if (interval.type !== type || interval.start >= bucketEnd || interval.end <= bucketStart) continue;
    const start = Math.max(interval.start, bucketStart);
    const end = Math.min(interval.end, bucketEnd);
    changes.set(start, (changes.get(start) || 0) + 1);
    changes.set(end, (changes.get(end) || 0) - 1);
  }
  let active = 0;
  let maximum = 0;
  for (const timestamp of [...changes.keys()].sort((left, right) => left - right)) {
    active += changes.get(timestamp);
    maximum = Math.max(maximum, active);
  }
  return maximum;
}

function dailyConcurrencyRows(report, locale) {
  const period = report.summary.period;
  const start = new Date(period.from).getTime();
  const end = new Date(period.to).getTime();
  if (!Number.isFinite(start) || !Number.isFinite(end) || end <= start) return [];
  const intervals = (report.summary.concurrencySessions || []).map((session) => sessionInterval(session, start, end)).filter(Boolean);
  const formatter = new Intl.DateTimeFormat(locale, { timeZone: period.timezone || report.timezone || "UTC", hour: "numeric" });
  const rows = [];
  for (let cursor = start; cursor < end; cursor += 60 * 60 * 1000) {
    const bucketEnd = Math.min(cursor + 60 * 60 * 1000, end);
    const values = Object.fromEntries(series.map(({ key }) => [key, maximumConcurrency(intervals, cursor, bucketEnd, key)]));
    rows.push({
      key: new Date(cursor).toISOString(),
      label: formatter.format(new Date(cursor)),
      values,
      total: series.reduce((sum, item) => sum + values[item.key], 0),
    });
  }
  return rows;
}

function niceScale(maximum, { integer = false, ticks = 4 } = {}) {
  const value = Math.max(integer ? 1 : 0.01, Number(maximum || 0));
  if (integer) {
    const tickCount = Math.min(ticks, Math.max(1, Math.ceil(value)));
    const step = Math.max(1, Math.ceil(value / tickCount));
    return { maximum: step * tickCount, step, tickCount };
  }
  const rawStep = value / ticks;
  const magnitude = 10 ** Math.floor(Math.log10(rawStep));
  const normalized = rawStep / magnitude;
  const multiplier = normalized <= 1 ? 1 : normalized <= 2 ? 2 : normalized <= 5 ? 5 : 10;
  const step = multiplier * magnitude;
  return { maximum: step * ticks, step, tickCount: ticks };
}

function chartFrame(height = 240) {
  const width = 720;
  const left = 58;
  const right = 16;
  const top = 18;
  const bottom = 34;
  return { width, height, left, right, top, bottom, chartWidth: width - left - right, chartHeight: height - top - bottom };
}

function gridMarkup(frame, scale, formatter) {
  return Array.from({ length: scale.tickCount + 1 }, (_, index) => {
    const value = index * scale.step;
    const y = frame.top + frame.chartHeight - (value / scale.maximum) * frame.chartHeight;
    return `<line x1="${frame.left}" y1="${y.toFixed(1)}" x2="${frame.width - frame.right}" y2="${y.toFixed(1)}" stroke="${colors.grid}" stroke-dasharray="3 5"/><text x="${frame.left - 8}" y="${(y + 3).toFixed(1)}" text-anchor="end">${escapeHtml(formatter(value))}</text>`;
  }).join("");
}

function legendMarkup(language) {
  return `<div class="chart-legend">${series.map((item) => `<span><i style="background:${colors[item.key]}"></i>${escapeHtml(activityTranslations[language][item.key])}</span>`).join("")}</div>`;
}

function lineSegments(rows, key, xFor, yFor) {
  const segments = [];
  let points = [];
  const flush = () => { if (points.length) segments.push(points); points = []; };
  rows.forEach((row, index) => {
    const value = row.values[key];
    if (value === null || value === undefined) flush();
    else points.push({ x: xFor(index), y: yFor(value), value, row });
  });
  flush();
  return segments;
}

function lineChart(rows, title, { language, valueFormatter, integer = false, peakLabel = "", xMode = "daily" }) {
  const frame = chartFrame(250);
  const maximumValue = Math.max(0, ...rows.flatMap((row) => series.map((item) => Number(row.values[item.key] || 0))));
  const scale = niceScale(maximumValue, { integer });
  const xFor = (index) => frame.left + (rows.length <= 1 ? frame.chartWidth / 2 : index / (rows.length - 1) * frame.chartWidth);
  const yFor = (value) => frame.top + frame.chartHeight - Number(value || 0) / scale.maximum * frame.chartHeight;
  const peakIndex = rows.reduce((winner, row, index) => row.total > (rows[winner]?.total ?? -1) ? index : winner, 0);
  const plots = series.map((item) => lineSegments(rows, item.key, xFor, yFor).map((points) => {
    const path = points.map((point, index) => `${index ? "L" : "M"}${point.x.toFixed(1)},${point.y.toFixed(1)}`).join(" ");
    const baseline = frame.top + frame.chartHeight;
    const area = `${path} L${points[points.length - 1].x.toFixed(1)},${baseline} L${points[0].x.toFixed(1)},${baseline} Z`;
    const dots = points.filter((_, index) => xMode === "hourly" ? index % 3 === 0 : index % 5 === 0).map((point) => `<circle cx="${point.x.toFixed(1)}" cy="${point.y.toFixed(1)}" r="2.5" fill="#fff" stroke="${colors[item.key]}" stroke-width="1.8"><title>${escapeHtml(point.row.label)} · ${escapeHtml(activityTranslations[language][item.key])}: ${escapeHtml(valueFormatter(point.value))}</title></circle>`).join("");
    return `<path d="${area}" fill="${colors[item.key]}" fill-opacity="0.10"/><path d="${path}" fill="none" stroke="${colors[item.key]}" stroke-width="2.5" stroke-linejoin="round"/>${dots}`;
  }).join("")).join("");
  const labelsMarkup = rows.map((row, index) => {
    const numericDay = Number(row.label);
    const visible = xMode === "hourly" ? index % 3 === 0 || index === rows.length - 1 : [1, 5, 10, 15, 20, 25, rows.length].includes(numericDay);
    return visible ? `<text x="${xFor(index).toFixed(1)}" y="${frame.height - 10}" text-anchor="middle"${row.future ? ` fill="${colors.axis}" opacity=".45"` : ""}>${escapeHtml(row.label)}</text>` : "";
  }).join("");
  const peakX = rows.length ? xFor(peakIndex) : frame.left;
  const peak = rows.length && rows[peakIndex]?.total > 0 ? `<line x1="${peakX.toFixed(1)}" y1="${frame.top}" x2="${peakX.toFixed(1)}" y2="${frame.top + frame.chartHeight}" stroke="${colors.axis}" stroke-dasharray="2 4" opacity=".7"/>` : "";
  return `<figure class="chart line-chart"><figcaption><span>${escapeHtml(title)}</span>${peakLabel ? `<small>${escapeHtml(peakLabel)}</small>` : ""}</figcaption>${legendMarkup(language)}<svg viewBox="0 0 ${frame.width} ${frame.height}" role="img" aria-label="${escapeHtml(title)}">${gridMarkup(frame, scale, valueFormatter)}${peak}${plots}${labelsMarkup}</svg></figure>`;
}

function volumeChart(rows, title, language) {
  const frame = chartFrame(190);
  const maximumValue = Math.max(0, ...rows.map((row) => Number(row.sessionTotal || 0)));
  const scale = niceScale(maximumValue, { integer: true });
  const slot = frame.chartWidth / Math.max(1, rows.length);
  const barWidth = Math.max(3, slot * 0.55);
  const bars = rows.map((row, index) => {
    const x = frame.left + index * slot + (slot - barWidth) / 2;
    const height = row.future ? 0 : Number(row.sessionTotal || 0) / scale.maximum * frame.chartHeight;
    const y = frame.top + frame.chartHeight - height;
    const visible = [1, 5, 10, 15, 20, 25, rows.length].includes(Number(row.label));
    const detail = series.map((item) => `${activityTranslations[language][item.key]} ${row.sessions[item.key] || 0}`).join(" · ");
    return `${row.future ? "" : `<rect x="${x.toFixed(1)}" y="${y.toFixed(1)}" width="${barWidth.toFixed(1)}" height="${height.toFixed(1)}" rx="2" fill="${colors.volume}"><title>${escapeHtml(row.tooltip)}: ${row.sessionTotal} · ${escapeHtml(detail)}</title></rect>`}${visible ? `<text x="${(x + barWidth / 2).toFixed(1)}" y="${frame.height - 10}" text-anchor="middle"${row.future ? " opacity=\".45\"" : ""}>${escapeHtml(row.label)}</text>` : ""}`;
  }).join("");
  return `<figure class="chart volume-chart"><figcaption>${escapeHtml(title)}</figcaption><svg viewBox="0 0 ${frame.width} ${frame.height}" role="img" aria-label="${escapeHtml(title)}">${gridMarkup(frame, scale, (value) => String(Math.round(value)))}${bars}</svg></figure>`;
}

function stackedYearChart(rows, title, { currencyCode, locale, language }) {
  const frame = chartFrame(260);
  const maximumValue = Math.max(0, ...rows.map((row) => row.total));
  const scale = niceScale(maximumValue);
  const slot = frame.chartWidth / Math.max(1, rows.length);
  const barWidth = Math.min(52, slot * 0.62);
  const bars = rows.map((row, index) => {
    const x = frame.left + index * slot + (slot - barWidth) / 2;
    let cursorY = frame.top + frame.chartHeight;
    const pieces = row.future ? `<text x="${(x + barWidth / 2).toFixed(1)}" y="${(cursorY - 5).toFixed(1)}" text-anchor="middle" class="future-mark">–</text>` : series.map((item) => {
      const height = row.values[item.key] / scale.maximum * frame.chartHeight;
      cursorY -= height;
      return `<rect x="${x.toFixed(1)}" y="${cursorY.toFixed(1)}" width="${barWidth.toFixed(1)}" height="${height.toFixed(1)}" fill="${colors[item.key]}"><title>${escapeHtml(row.label)} · ${escapeHtml(activityTranslations[language][item.key])}: ${escapeHtml(currency(row.values[item.key], currencyCode, locale))}</title></rect>`;
    }).join("");
    const total = !row.future && row.total > 0 ? `<text x="${(x + barWidth / 2).toFixed(1)}" y="${Math.max(11, cursorY - 7).toFixed(1)}" text-anchor="middle" class="bar-total">${escapeHtml(currency(row.total, currencyCode, locale))}</text>` : "";
    return `${pieces}${total}<text x="${(x + barWidth / 2).toFixed(1)}" y="${frame.height - 10}" text-anchor="middle"${row.future ? " opacity=\".45\"" : ""}>${escapeHtml(row.label)}</text>`;
  }).join("");
  return `<figure class="chart stacked-chart"><figcaption>${escapeHtml(title)}</figcaption>${legendMarkup(language)}<svg viewBox="0 0 ${frame.width} ${frame.height}" role="img" aria-label="${escapeHtml(title)}">${gridMarkup(frame, scale, (value) => compactCurrency(value, currencyCode, locale))}${bars}</svg></figure>`;
}

function chartSection(report, copy, locale, language) {
  const currencyCode = report.summary.period.currency;
  if (report.reportType === "daily") {
    const rows = dailyConcurrencyRows(report, locale);
    const peak = rows.reduce((winner, row) => !winner || row.total > winner.total ? row : winner, null);
    const peakDetail = peak?.total ? `${copy.peak}: ${peak.label} · ${peak.total} ${copy.sessionsField}` : "";
    const peakLabel = `${copy.businessDay}${peakDetail ? ` · ${peakDetail}` : ""}`;
    return lineChart(rows, copy.dailyChart, { language, valueFormatter: (value) => String(Math.round(value)), integer: true, peakLabel, xMode: "hourly" });
  }
  if (report.reportType === "monthly") {
    const rows = monthlyRows(report, locale);
    const peak = rows.filter((row) => !row.future).reduce((winner, row) => !winner || row.total > winner.total ? row : winner, null);
    const peakLabel = peak?.total ? `${copy.peak}: ${peak.tooltip} · ${currency(peak.total, currencyCode, locale)}` : "";
    return `${lineChart(rows, copy.monthlyChart, { language, valueFormatter: (value) => currency(value, currencyCode, locale), peakLabel })}${volumeChart(rows, copy.monthlyVolume, language)}`;
  }
  return stackedYearChart(yearlyRows(report, locale), copy.yearlyChart, { currencyCode, locale, language });
}

function formatSessionTime(value, timezone, locale, fallback) {
  if (!value) return fallback;
  return new Intl.DateTimeFormat(locale, { timeZone: timezone, month: "short", day: "numeric", hour: "numeric", minute: "2-digit" }).format(new Date(value));
}

function details(report, currencyCode, locale, copy, language) {
  let rows;
  let headings;
  if (report.reportType === "daily") {
    headings = [copy.period, copy.activity, copy.station, copy.controllers, copy.duration, copy.revenueField, copy.status];
    rows = report.summary.sessions.map((item) => [
      `${formatSessionTime(item.startedAt, report.timezone, locale, copy.inProgress)} → ${formatSessionTime(item.endedAt, report.timezone, locale, copy.inProgress)}`,
      activityTranslations[language][item.activity] ?? item.activityLabel,
      item.stationNumber ?? "—",
      item.activity === "playstation" ? item.controllerCount ?? 1 : "—",
      item.status === "completed" ? duration(item.durationSeconds) : copy.inProgress,
      item.status === "completed" ? currency(item.revenue, currencyCode, locale) : "—",
      item.status,
    ]);
  } else {
    headings = [copy.period, copy.sessionsField, copy.playingTime, copy.revenueField];
    rows = (report.reportType === "monthly" ? report.summary.days : report.summary.months)
      .filter((item) => item.total.sessions || item.total.revenue)
      .map((item) => [item.key, item.total.sessions, duration(item.total.totalSeconds), currency(item.total.revenue, currencyCode, locale)]);
  }
  return `<div class="table-wrap"><table><thead><tr>${headings.map((item) => `<th>${escapeHtml(item)}</th>`).join("")}</tr></thead><tbody>${rows.length ? rows.map((row) => `<tr>${row.map((item) => `<td>${escapeHtml(item)}</td>`).join("")}</tr>`).join("") : `<tr><td colspan="${headings.length}" class="empty">${escapeHtml(copy.empty)}</td></tr>`}</tbody></table></div>`;
}

